const interestCandidates = [
  {name: '小陈', scores: [9, 2]},
  {name: '小林', scores: [7, 9]},
];
const interestRules = [
  {label: '只看音乐', weights: [1, 0]},
  {label: '只看电影', weights: [0, 1]},
];
const interestScore = ({scores}, {weights}) => scores.reduce((sum, score, i) => sum + score * weights[i], 0);

const softmaxCandidates = [
  {name: '书', logit: 2},
  {name: '杂志', logit: 1},
  {name: '笔记本', logit: 0},
];
function temperatureDistribution(temperature) {
  const exponentials = softmaxCandidates.map(candidate => Math.exp(candidate.logit / temperature));
  const total = exponentials.reduce((sum, x) => sum + x, 0);
  return softmaxCandidates.map((candidate, i) => ({
    ...candidate,
    scaled: candidate.logit / temperature,
    exponential: exponentials[i],
    probability: 100 * exponentials[i] / total,
  }));
}
